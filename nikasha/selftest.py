"""selftest — repo consistency checks. Prints one line per check and ends with SELFTEST GREEN (exit 0)
or SELFTEST RED (exit 1). GREEN means every line is PASS, SKIP or WARN; a single FAIL makes it RED.

Checks:
  a  fit ids and exam ids are disjoint and both files are non-empty. Only the "id" field of each row is
     read; no request or function text is kept or printed (brief rule 4 / Task 6).
  b  every item of every results gauge file (top-level results/*.json carrying "gauge" and a list "items")
     has probs_raw of length 3, entries in [0, 1], sum within 1e-6 of 1 (the gauge contract). A gauge
     file whose item count differs from n_fit + n_exam, and any interrupted-run checkpoint
     (results/*.partial.json or "partial": true), is a FAIL: a truncated gauge file is not a gauge.
  c  every number printed in README.md occurs in results/*.json (including .calib.json) or
     data/seta/manifest.json, compared through decimal.Decimal (rule 10: no number by hand). The
     allowed set is built exactly as specified: JSON numbers (repr and str) and number tokens inside
     JSON string VALUES; dict keys and the absolute value of negative numbers are not consulted.
  d  one license line per distinct non-"constant" engine named in results gauge files:
     cards/<engine>.md exists and has a line starting with "license:".
  e  sha256(exam.jsonl) and sha256(fit.jsonl) equal the manifest's.
  f  every exam.scored_at is preceded by a commit of PREREG.md (rule 9): the version in force at scoring
     time is the latest PREREG.md commit before it, and an exam block that records `prereg_commit` must
     name exactly that commit's date. PREREG.md is amended, never rewritten: every later committed version
     (and the working tree) starts with the full text in force at the first exam block. SKIP while no
     exam block exists.
  g  README.md exists, carries the readme.py marker, and is at least as new as the JSON it depends on
     (WARN, not FAIL, when older). results/*.partial.json and results/timing-*.json are not README
     inputs and are left out of that comparison.
  h  every results/<gauge>.calib.json carries fit_fingerprint and it equals nikasha.fit_fingerprint of
     results/<gauge>.json (sha256 over sorted fit ids + logits_mean): the calibration belongs to this run.
     An exam block that records fit_fingerprint must match it too; score.py's guard refuses a tampered run.
  i  PREREG Amendment 1 (Gate 4): its commit predates every new exam block, each block records it, the Gate 3
     blocks predate it, and it is on HEAD (WARN while not yet on origin/main, e.g. before a force-push).
  j  gauge ③'s fit-split logits are flagged oof: true and reproduce as out-of-fold values by refitting per fold.
  k  no key material anywhere in the repo: the key prefix is in no file (.git included) and in no commit.

Run from the repo root:  ~/venvs/nikasha/bin/python -m nikasha.selftest
This module never imports an engine and never prints the text of any set-A item.
"""
from __future__ import annotations

