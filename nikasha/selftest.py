# --------------------------------------------------------------------------- main


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        prog="nikasha.selftest",
        description="Repo consistency checks (a-k); prints SELFTEST GREEN and exits 0, or SELFTEST RED and exits 1.",
    )
    ap.add_argument("--strict", action="store_true", help="treat WARN lines as FAIL")
    args = ap.parse_args(argv)

    repo = Repo()
    lines: list[tuple[str, str, str]] = []
    for letter, fn in CHECKS:
        try:
            lines.extend(fn(repo))
        except Exception as exc:  # noqa: BLE001 — a crashing check is itself a FAIL, not an abort
            lines.append((FAIL, letter, f"check crashed: {type(exc).__name__}: {exc}"))

    for status, letter, msg in lines:
        print(f"{status} [{letter}] {msg}")

    counts = {s: sum(1 for st, _, _ in lines if st == s) for s in (PASS, FAIL, WARN, SKIP)}
    red = counts[FAIL] > 0 or (args.strict and counts[WARN] > 0)
    print(f"checks: {counts[PASS]} PASS, {counts[FAIL]} FAIL, {counts[WARN]} WARN, {counts[SKIP]} SKIP")
    print("SELFTEST RED" if red else "SELFTEST GREEN")
    return 1 if red else 0


